'use client';
import React, { createContext, useContext, useEffect, useMemo, useState } from 'react';
import en from '../../messages/en.json';
import zhCN from '../../messages/zh-CN.json';
import es from '../../messages/es.json';
import fr from '../../messages/fr.json';
import ptBR from '../../messages/pt-BR.json';
import ar from '../../messages/ar.json';
import { Profile, emptyProfile } from '../lib/types';
import { applyProfilePatch } from '../lib/profile';
import { deriveChecklist, mergeChecklist, type ChecklistItem, type ChecklistProgramme } from '../lib/tracking';

export type Locale = 'en' | 'zh-CN' | 'es' | 'fr' | 'pt-BR' | 'ar';
export const LOCALES: { code: Locale; label: string }[] = [
  { code: 'en', label: 'English' },
  { code: 'zh-CN', label: '简体中文' },
  { code: 'es', label: 'Español' },
  { code: 'fr', label: 'Français' },
  { code: 'pt-BR', label: 'Português (Brasil)' },
  { code: 'ar', label: 'العربية' },
];
const MESSAGES: Record<Locale, Record<string, string>> = {
  en: en as Record<string, string>,
  'zh-CN': zhCN as Record<string, string>,
  es: es as Record<string, string>,
  fr: fr as Record<string, string>,
  'pt-BR': ptBR as Record<string, string>,
  ar: ar as Record<string, string>,
};
export const RTL_LOCALES: Locale[] = ['ar'];

interface AppState {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
  /** Localised string with {placeholder} interpolation. */
  tf: (key: string, vars?: Record<string, string | number>) => string;
  profile: Profile;
  setProfile: (p: Profile) => void;
  updateProfile: (patch: Partial<Profile>) => void;
  clearData: () => void;
  /** Bumps every time clearData runs, so components holding local
   * banner/modal state (e.g. WelcomeBanner) can close themselves at
   * once instead of waiting for a manual close. */
  bannerClearNonce: number;
  /** Bumps every time clearData runs (same pattern as
   * bannerClearNonce): components holding wizard/chat position in
   * local state — the wizard step, which useState only initialises
   * at mount — reset themselves at once instead of sitting on a
   * stale step for a profile that no longer exists (round 18). */
  dataClearNonce: number;
  /** True once the saved locale/profile have been read from
   * localStorage (round 18): child effects run before the
   * provider's hydration effect, so a page that matches on mount
   * must wait for this instead of reading the empty profile. */
  hydrated: boolean;
  /** Restyle 2 (Gen UI behaviour): the follow-up application
   * checklist — deadline / documents / visa steps derived from the
   * stored profile + verified programme data only (see
   * lib/tracking.ts deriveChecklist). Done flags persist in
   * localStorage (pp-checklist) like the profile; derivation
   * re-runs when the profile changes, preserving done flags by id.
   * Nothing here is a model output: the checklist is never
   * generated by the AI, only derived from stored + verified data. */
  checklist: ChecklistItem[];
  /** Flip one step's done flag (persists). */
  toggleChecklistItem: (id: string) => void;
  /** Re-derive the checklist from the given profile + verified
   * programmes, keeping done flags by id. Callers pass the
   * programmes (the store holds no catalogue). */
  refreshChecklist: (profile: Profile, programmes: ChecklistProgramme[]) => void;
}

const Ctx = createContext<AppState | null>(null);

export function AppProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('en');
  const [profile, setProfileState] = useState<Profile>(emptyProfile);
  const [hydrated, setHydrated] = useState(false);
  const [bannerClearNonce, setBannerClearNonce] = useState(0);
  const [dataClearNonce, setDataClearNonce] = useState(0);
  // Restyle 2: the follow-up checklist, persisted like the profile.
  const [checklist, setChecklistState] = useState<ChecklistItem[]>([]);

  useEffect(() => {
    try {
      const savedLocale = localStorage.getItem('pp-locale') as Locale | null;
      if (savedLocale && MESSAGES[savedLocale]) setLocaleState(savedLocale);
      const savedProfile = localStorage.getItem('pp-profile');
      if (savedProfile) setProfileState({ ...emptyProfile, ...JSON.parse(savedProfile) });
      const savedChecklist = localStorage.getItem('pp-checklist');
      if (savedChecklist) {
        const parsed = JSON.parse(savedChecklist) as ChecklistItem[];
        if (Array.isArray(parsed)) setChecklistState(parsed.filter((i) => i && typeof i.id === 'string' && typeof i.kind === 'string'));
      }
    } catch { /* ignore corrupt local storage */ }
    setHydrated(true);
  }, []);

  useEffect(() => {
    if (!hydrated) return;
    localStorage.setItem('pp-checklist', JSON.stringify(checklist));
  }, [checklist, hydrated]);

  useEffect(() => {
    if (!hydrated) return;
    document.documentElement.lang = locale;
    document.documentElement.dir = RTL_LOCALES.includes(locale) ? 'rtl' : 'ltr';
    localStorage.setItem('pp-locale', locale);
  }, [locale, hydrated]);

  useEffect(() => {
    if (!hydrated) return;
    localStorage.setItem('pp-profile', JSON.stringify(profile));
  }, [profile, hydrated]);

  const setLocale = (l: Locale) => setLocaleState(l);
  const setProfile = (p: Profile) => setProfileState(p);
  // Restyle 2: flip one checklist step; re-derive from profile +
  // verified programmes, preserving done flags by id.
  const toggleChecklistItem = (id: string) =>
    setChecklistState((prev) => prev.map((i) => (i.id === id ? { ...i, done: !i.done } : i)));
  const refreshChecklist = (p: Profile, programmes: ChecklistProgramme[]) =>
    setChecklistState((prev) => mergeChecklist(prev, deriveChecklist(p, programmes)));
  // Round 31 G3: any user edit clears the synthetic-sample marker
  // (applyProfilePatch forces the marker off), so the "Synthetic
  // sample" banner only shows while the synthetic sample IS the
  // active profile. Loading a sample goes through setProfile, not
  // here, so a freshly loaded sample keeps its banner.
  const updateProfile = (patch: Partial<Profile>) => setProfileState((prev) => applyProfilePatch(prev, patch));
  const clearData = () => {
    setProfileState(emptyProfile);
    // Restyle 2: the checklist belongs to the cleared profile — a
    // cleared profile with a surviving checklist would list steps
    // for programmes the user no longer tracks.
    setChecklistState([]);
    try { localStorage.removeItem('pp-checklist'); } catch { /* ignore */ }
    // Round 11, F6: the WelcomeBanner keeps its own open/closed state
    // and never heard about clearData, so it kept showing
    // "欢迎回来！你的资格检查已完成" until manually closed. Bump the
    // nonce so it closes itself at once.
    setBannerClearNonce((n) => n + 1);
    // Round 18, P0/P1: clearing only the form values left the wizard
    // sitting on its (stale) step — "开始资格检查" landed straight on
    // the step-8 empty state. The stored step and the pref-chat
    // position go too, and dataClearNonce tells the mounted wizard
    // to reset its live step state at once (useState only
    // initialises at mount, so removing the key alone is not enough
    // while the page stays mounted).
    setDataClearNonce((n) => n + 1);
    try { localStorage.removeItem('pp-profile'); localStorage.removeItem('pp-check-done'); localStorage.removeItem('pp-wizard-step'); localStorage.removeItem('pp-prefchat'); } catch { /* ignore */ }
  };
  const t = (key: string) => MESSAGES[locale][key] ?? MESSAGES.en[key] ?? key;
  const tf = (key: string, vars?: Record<string, string | number>) => {
    let s = t(key);
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    }
    return s;
  };

  const value = useMemo(() => ({ locale, setLocale, t, tf, profile, setProfile, updateProfile, clearData, bannerClearNonce, dataClearNonce, hydrated, checklist, toggleChecklistItem, refreshChecklist }),
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [locale, profile, bannerClearNonce, dataClearNonce, hydrated, checklist]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useApp(): AppState {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useApp must be used inside AppProvider');
  return ctx;
}
