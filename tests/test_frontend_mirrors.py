"""Frontend offline mirrors stay in sync with the expansion sources.

The mirrors (frontend/src/lib/expansion.ts, frontend/src/lib/cases.ts)
are generated by tools/generate_frontend_mirrors.py. If a test here fails,
re-run the generator — never hand-edit the generated files.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPANSION_SRC = ROOT / "data" / "expansions" / "expansion.json"
CASES_SRC = ROOT / "data" / "expansions" / "success_cases.json"
EXPANSION_TS = ROOT / "frontend" / "src" / "lib" / "expansion.ts"
CASES_TS = ROOT / "frontend" / "src" / "lib" / "cases.ts"


def _ts_ids(path: Path) -> set[str]:
    # Programme/case objects open with "id":"..." followed immediately by
    # their next field ("institutionId" / "platform"); source and
    # requirement ids appear in nested positions and must not match.
    text = path.read_text(encoding="utf-8")
    prog = set(re.findall(r'"id":"([a-z0-9][a-z0-9\-]*)","institutionId"', text))
    cases = set(re.findall(r'"id":"([a-z0-9][a-z0-9\-]*)","platform"', text))
    return prog | cases


def test_expansion_mirror_matches_source():
    src = json.loads(EXPANSION_SRC.read_text(encoding="utf-8"))
    # The file keeps growing as new bands merge (366 computer programmes
    # on 2026-11-25, then a business band); the mirror must match the
    # source exactly, whatever the current count.
    assert len(src["programs"]) >= 366
    src_ids = {p["id"] for p in src["programs"]}
    assert _ts_ids(EXPANSION_TS) == src_ids
    # Every mirrored programme keeps at least one requirement and every
    # requirement's source ids resolve to a source on the same programme.
    text = EXPANSION_TS.read_text(encoding="utf-8")
    assert text.count('"requirements":') == len(src["programs"])
    for p in src["programs"]:
        assert p.get("requirements"), p["id"]
        known = {s["id"] for s in p.get("sources") or []}
        for r in p["requirements"]:
            for sid in r.get("source_ids") or []:
                assert sid in known, (p["id"], sid)


def test_cases_mirror_matches_source():
    src = json.loads(CASES_SRC.read_text(encoding="utf-8"))
    # Round 8 dedupe: one card per applicant — 41 cards covering 53 offers
    # (was 55 one-offer records; 4 applicants were split across cards and
    # 2 non-stories were removed).
    assert len(src["cases"]) == 41
    assert src["meta"]["total_cases"] == 41
    assert src["meta"]["total_offers"] == 53
    assert sum(len(c["offers"]) for c in src["cases"]) == 53
    src_ids = {c["id"] for c in src["cases"]}
    assert _ts_ids(CASES_TS) == src_ids
    # Every case keeps its label and a source URL; no case gains a field
    # the source does not have. Every card lists at least one offer, every
    # offer names an institution and a level, and no '同上' filler survives
    # the merge — each offer carries its own content.
    raw = CASES_SRC.read_text(encoding="utf-8")
    assert "同上" not in raw
    assert "sc-054" not in src_ids and "sc-055" not in src_ids
    for c in src["cases"]:
        assert c["label"] == "网友分享，未经官方核实", c["id"]
        assert c["source_url"], c["id"]
        assert c["offers"], c["id"]
        if c["platform"] == "The GradCafe":
            assert c.get("source_ref"), c["id"]  # listing locator, no per-record URL
        for o in c["offers"]:
            assert o["institution"] and o["level"], (c["id"], o)
    text = CASES_TS.read_text(encoding="utf-8")
    assert "FEATURED_CASE_IDS" in text
    for fid in ["sc-001", "sc-026", "sc-051", "sc-033", "sc-012", "sc-039"]:
        assert fid in src_ids


REVIEWS_SRC = ROOT / "data" / "expansions" / "school_reviews.json"
REVIEWS_TS = ROOT / "frontend" / "src" / "lib" / "reviews.ts"


def test_reviews_mirror_matches_source():
    # The source file is collected by another agent; it may not exist
    # yet — in that case the mirror must be the empty array (the
    # generator writes it), never a stale copy.
    if not REVIEWS_SRC.exists():
        assert json.loads(REVIEWS_TS.read_text(encoding="utf-8").split("=", 1)[1].rstrip(";\n")) == []
        return
    src = json.loads(REVIEWS_SRC.read_text(encoding="utf-8"))
    src_ids = {r["id"] for r in src["reviews"]}
    assert len(src_ids) == len(src["reviews"])  # ids unique
    text = REVIEWS_TS.read_text(encoding="utf-8")
    ts_ids = set(re.findall(r'"id":"([a-z0-9][a-z0-9\-]*)","institutionId"', text))
    assert ts_ids == src_ids
    # Every review keeps a verbatim quote, the unverified label and a
    # source URL; no review gains a rating — there is no rating data.
    for r in src["reviews"]:
        assert (r.get("quote") or "").strip(), r["id"]
        assert r["label"] == "网友分享，未经官方核实", r["id"]
        assert r["source_url"], r["id"]
        assert "rating" not in r and "stars" not in r, r["id"]
    assert '"rating"' not in text and '"stars"' not in text


def test_carousel_cards_have_no_stars():
    # The reference video's cards show 5 stars; PathPilot has no rating
    # data anywhere, so no carousel card may render one.
    root = ROOT / "frontend" / "src" / "components"
    for name in ["CaseCard.tsx", "NewsCard.tsx", "ReviewCard.tsx", "FanCarousel.tsx"]:
        text = (root / name).read_text(encoding="utf-8")
        assert "★" not in text and "☆" not in text, name
        assert '"rating"' not in text and "rating=" not in text, name


# Round 9 (R5): verified language of instruction — the field must survive
# the mirror generation (data/expansions/expansion.json ->
# frontend/src/lib/expansion.ts) verbatim, so the UI can show it with
# its official source. Only programmes whose official page states the
# teaching language carry it; it is never guessed.
SWISS_LOI = {
    "eth-cs-bsc-2027": ("German", "https://ethz.ch/en/studies/bachelor/application/bachelor-human-medicine/application-admission/language-requirements.html"),
    "eth-cse-bsc-2027": ("German", "https://ethz.ch/en/studies/bachelor/application/bachelor-human-medicine/application-admission/language-requirements.html"),
    "epfl-cs-bsc-2027": ("French", "https://www.epfl.ch/campus/services/internal-trainings/language-centre/language-tests-and-questions/languages-taught-and-international-tests/"),
    "epfl-ai-bsc-2027": ("French", "https://www.epfl.ch/campus/services/internal-trainings/language-centre/language-tests-and-questions/languages-taught-and-international-tests/"),
    # Verified correction (2026-11-26): UZH Informatics BSc is
    # GERMAN-taught (main language of instruction: German), not
    # English — the official degrees page states it, and the IfI page
    # requires a German C1 certificate.
    "zurich-informatics-bsc-2027": ("German", "https://www.degrees.uzh.ch/en/bachelor/50000003/51082599/51085518"),
}


def _load_expansion_mirror() -> list[dict]:
    text = EXPANSION_TS.read_text(encoding="utf-8")
    # The header comment contains '=' — split on the export assignment.
    payload = text[text.index(" = [") + 3:].strip().rstrip(";")
    return json.loads(payload)


def test_language_of_instruction_survives_mirror():
    src = json.loads(EXPANSION_SRC.read_text(encoding="utf-8"))
    src_by_id = {p["id"]: p for p in src["programs"]}
    mirror = {p["id"]: p for p in _load_expansion_mirror()}
    for pid, (language, url) in SWISS_LOI.items():
        prog = src_by_id[pid]
        loi = prog.get("language_of_instruction")
        assert loi, pid
        assert loi["language"] == language, pid
        assert loi["source_url"] == url, pid
        assert loi["source_url"].startswith("https://"), pid
        # The source URL must be one of the programme's own listed
        # sources (traceability — the UI links to it).
        assert url in {s["url"] for s in prog["sources"]}, pid
        # And the mirror must carry the same facts, converted to the
        # frontend's camelCase shape (language + note + sourceUrl).
        assert mirror[pid].get("languageOfInstruction") == {
            "language": loi["language"],
            "note": loi["note"],
            "sourceUrl": loi["source_url"],
        }, pid
    # Nothing else gains the field: only the five verified programmes.
    with_loi = {pid for pid, p in mirror.items() if p.get("languageOfInstruction")}
    assert with_loi == set(SWISS_LOI), with_loi
